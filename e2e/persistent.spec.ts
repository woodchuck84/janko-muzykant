  await expect.poll(() => dock.locator('audio').evaluateAll(nodes => nodes.filter(audio => !audio.paused && audio.currentTime > 0.2).length === 1)).toBe(true)
  await expect(module.getByRole('button', { name: 'Pauza', exact: true })).toBeVisible()
  await module.getByRole('button', { name: 'Pauza', exact: true }).click()
  await expect(dock.getByRole('button', { name: 'Odtwórz', exact: true })).toBeVisible()
