  const noBass = { id: 'song-without-bass', name: 'Bez basu', event_ids: ['fixture-event'],
    files: [{ ...songs[0].files.find(file => file.part === 'S' && file.kind === 'audio')!, id: 's-only' }] }
  await page.route('**/api/library', route => route.fulfill({ json: { ...library, songs: [...songs, noAudio, noBass], events: [{ id: 'fixture-event', name: 'Koncert' }] } }))
  await page.goto('/')
  await page.getByLabel('Mój głos', { exact: true }).selectOption('B')
  await page.getByLabel('Filtr wydarzeń').selectOption('fixture-event')
  await page.locator('.song-card').filter({ hasText: 'Piechota' }).click()
  const module = page.locator('#player-details')
  const dock = page.locator('.persistent-player')
  await expect(module.getByRole('heading', { name: 'Posłuchaj. Powtórz. Zaśpiewaj.' })).toBeVisible()
