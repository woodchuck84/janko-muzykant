import { test, expect } from '@playwright/test'
import path from 'node:path'

const artifactDir = process.env.JANKO_SCREENSHOTS
test('real repertoire, PDF, audio, loops, bookmarks, mixer, MusicXML and offline', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Co dziś zaśpiewasz?' })).toBeVisible()
  await expect(page.locator('.song-card')).not.toHaveCount(0)
  if (artifactDir) await page.screenshot({ path: path.join(artifactDir, 'library.png') })
  await page.getByLabel('Mój głos', { exact: true }).selectOption('AI')
  await page.locator('.song-card').filter({ has: page.getByRole('heading', { name: 'Piechota', exact: true }) }).click()
  await expect(page.getByRole('heading', { name: 'Piechota', exact: true })).toBeVisible()
  await expect(page.locator('canvas')).toBeVisible()
  await expect.poll(() => page.locator('canvas').evaluate(canvas => canvas.width)).toBeGreaterThan(100)
  const module = page.locator('#player-details')
  await module.getByRole('button', { name: 'Odtwórz', exact: true }).click()
  await expect.poll(() => page.locator('audio').evaluateAll(audios => audios.some(audio => audio.currentTime > 1 && !audio.paused))).toBe(true)
  await module.getByRole('button', { name: 'Pauza', exact: true }).click()
  await module.locator('#speed-page').fill('0.75')
  await expect.poll(() => page.locator('audio').evaluateAll(audios => audios.some(audio => audio.readyState > 0 && audio.playbackRate === 0.75 && audio.preservesPitch))).toBe(true)
  await module.getByRole('button', { name: /^A / }).click()
  await module.getByLabel('Pozycja nagrania').fill('6')
  await module.getByRole('button', { name: /^B / }).click()
  await module.getByRole('button', { name: 'Pętla', exact: true }).click()
  await module.getByRole('button', { name: 'Odtwórz', exact: true }).click()
  await page.waitForTimeout(8000)
  const loopTime = await page.locator('audio').evaluateAll(audios => audios.find(audio => !audio.paused)?.currentTime)
  expect(loopTime).toBeGreaterThan(0)
  expect(loopTime).toBeLessThan(6)
  await module.getByRole('button', { name: 'Pauza', exact: true }).click()
  await module.getByLabel('Nazwa zakładki').fill('takt 17')
  await module.getByRole('button', { name: 'Dodaj zakładkę' }).click()
  await expect(page.getByRole('button', { name: /takt 17/ }).first()).toBeVisible()
  if (artifactDir) await page.screenshot({ path: path.join(artifactDir, 'practice.png'), fullPage: true })
  await module.getByRole('button', { name: 'Z chórem', exact: true }).click()
  await module.getByRole('button', { name: 'Odtwórz', exact: true }).click()
  await expect.poll(() => page.locator('audio').evaluateAll(audios => audios.filter(audio => !audio.paused && audio.currentTime > 0).length)).toBeGreaterThan(1)
  await module.getByRole('button', { name: 'Pauza', exact: true }).click()
  await module.getByRole('button', { name: 'Bez mojego', exact: true }).click()
  await expect(module.getByLabel('Głośność A', { exact: true })).toHaveValue('0')
  await page.getByRole('button', { name: 'Analiza i generowanie' }).click()
  await expect(page.getByLabel('Linia do analizy').locator('option')).not.toHaveCount(1, { timeout: 150000 })
  // The actual Piechota OMR has generic names; choose the alto staff before either action.
  await page.getByLabel('Linia do analizy').selectOption('P2')
  await page.getByRole('button', { name: 'Analizuj partyturę' }).click()
  await expect(page.getByText('Zakres Twojej linii', { exact: true })).toBeVisible({ timeout: 150000 })
  await page.getByRole('button', { name: 'Generuj nagranie' }).click()
  await expect(page.locator('.generated-audio audio')).toBeVisible()
  await expect(page.locator('.rendered-score svg').first()).toBeVisible()
  await page.locator('.generated-audio audio').evaluate(audio => audio.play())
  await expect.poll(() => page.locator('.generated-audio audio').evaluate(audio => audio.currentTime)).toBeGreaterThan(1)
  await page.locator('.generated-audio audio').evaluate(audio => audio.pause())
  if (artifactDir) await page.screenshot({ path: path.join(artifactDir, 'analysis.png') })
  await page.getByRole('button', { name: 'Zapisz offline' }).click()
  await expect(page.getByRole('status')).toContainText('Zapisano lokalnie', { timeout: 150000 })
  await page.reload()
  await expect(page.getByLabel('Mój głos', { exact: true })).toHaveValue('AI')
  await page.getByRole('button', { name: 'Nuty i nagrania' }).click()
  await expect(page.getByRole('button', { name: /takt 17/ }).first()).toBeVisible()
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    await fetch('/api/library')
    await fetch('/api/config')
  })
  await page.context().setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Piechota', exact: true })).toBeVisible()
  await expect(page.locator('canvas')).toBeVisible()
  await page.locator('#player-details').getByRole('button', { name: 'Odtwórz', exact: true }).click()
  await expect.poll(() => page.locator('audio').evaluateAll(audios => audios.some(audio => audio.currentTime > 1 && !audio.paused))).toBe(true)
  await page.context().setOffline(false)
  expect(errors).toEqual([])
})

test('mobile library is usable without horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('.song-card').first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  if (artifactDir) await page.screenshot({ path: path.join(artifactDir, 'mobile.png'), fullPage: true })
})
