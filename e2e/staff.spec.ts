import { test, expect } from '@playwright/test'
import path from 'node:path'

const screenshots = process.env.JANKO_SCREENSHOTS
test.use({ actionTimeout: 20000 })

test('unnamed Piechota bass staff can be selected before analysis and reused for local WAV and Coaching', async ({ page }) => {
  await page.goto('/?song=b66a67c3f13dd000ff0b')
  await page.getByLabel('Mój głos', { exact: true }).selectOption('B')
  await page.evaluate(() => {
    for (let index = localStorage.length - 1; index >= 0; index--) {
      const key = localStorage.key(index)!
      if (key.startsWith('janko.staff.b66a67c3f13dd000ff0b.') && key.endsWith('.B')) localStorage.removeItem(key)
    }
  })
  const analysisRequests: string[] = []
  page.on('request', request => {
    if (request.url().endsWith('/analyze')) analysisRequests.push(request.url())
  })
  await page.getByRole('button', { name: 'Analiza i generowanie', exact: true }).click()
  await expect(page.getByLabel('Linia do analizy')).toBeEnabled()
  expect(analysisRequests).toHaveLength(0)
  await expect(page.getByRole('button', { name: 'Analizuj partyturę', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Generuj nagranie', exact: true })).toBeDisabled()
  await expect(page.getByLabel('Linia do analizy').locator('option[value="P3"]')).toContainText('G2–G3')
  await expect(page.getByLabel('Linia do analizy')).toHaveValue('P3')
  await expect(page.getByText(/To tylko sugestia, nie rozpoznanie głosu/)).toBeVisible()
  await page.getByRole('button', { name: 'Potwierdź wskazaną pięciolinię', exact: true }).click()
  await page.getByRole('button', { name: 'Analizuj partyturę', exact: true }).click()
  await expect(page.getByText('Zakres Twojej linii', { exact: true })).toBeVisible()
  await expect(page.locator('.analysis-stats')).toContainText('G2 — G3')
  await expect(page.locator('[role="alert"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Generuj nagranie', exact: true }).click()
  await expect(page.locator('.generated-audio audio')).toBeVisible()
  await expect(page.locator('.local-output')).toContainText('data\\generated\\')
  const download = page.getByRole('link', { name: 'Pobierz przewodnik WAV', exact: true })
  const downloadEvent = page.waitForEvent('download')
  await download.click()
  expect((await downloadEvent).suggestedFilename()).toMatch(/^[a-f0-9]{32}\.wav$/)
  await page.locator('.generated-audio audio').evaluate(audio => audio.play())
  await expect.poll(() => page.locator('.generated-audio audio').evaluate(audio => audio.currentTime)).toBeGreaterThan(0.2)
  await page.locator('.generated-audio audio').evaluate(audio => audio.pause())
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('janko.coach.b66a67c3f13dd000ff0b.B')!).analysis.selected_part.id)).toBe('P3')
  if (screenshots) {
    await page.locator('.analysis-controls').screenshot({ path: path.join(screenshots, 'staff-selection.png') })
    await page.locator('.generated-audio').screenshot({ path: path.join(screenshots, 'generated-guide.png') })
  }
  await page.reload()
  await page.getByRole('button', { name: 'Analiza i generowanie', exact: true }).click()
  await expect(page.getByLabel('Linia do analizy')).toHaveValue('P3')
  await page.getByRole('button', { name: 'Coaching', exact: true }).click()
  await expect(page.getByText(/Cel z partii P3/)).toBeVisible()
  await page.getByRole('button', { name: 'Analiza i generowanie', exact: true }).click()
  await expect(page.getByLabel('Linia do analizy')).toHaveValue('P3')
  await page.getByLabel('Linia do analizy').selectOption('P2')
  expect(await page.evaluate(() => localStorage.getItem('janko.coach.b66a67c3f13dd000ff0b.B'))).toBeNull()
  await page.getByLabel('Linia do analizy').selectOption('P3')
  const pdfId = await page.getByLabel('Źródło analizy').locator('option').filter({ hasText: /^PDF/ }).first().getAttribute('value')
  if (!pdfId) throw new Error('The live Piechota PDF is missing')
  await page.getByLabel('Źródło analizy').selectOption(pdfId)
  await page.getByRole('button', { name: 'Odczytaj linie partytury', exact: true }).click()
  await expect(page.getByLabel('Linia do analizy')).toBeEnabled({ timeout: 150000 })
  await page.getByLabel('Linia do analizy').selectOption('P3')
  await page.getByRole('button', { name: 'Generuj nagranie', exact: true }).click()
  await expect(page.locator('.generated-audio audio')).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('janko.coach.b66a67c3f13dd000ff0b.B')!).analysis.selected_part.id)).toBe('P3')
})

test('mixer explanation supports keyboard, click and mobile without overflow', async ({ page }) => {
  await page.goto('/?song=b66a67c3f13dd000ff0b')
  const info = page.getByRole('button', { name: 'Jak działa mikser chóru?', exact: true })
  await info.focus()
  const tooltip = page.getByRole('tooltip')
  await expect(tooltip).toBeVisible()
  await expect(tooltip).toContainText('osobne, istniejące nagrania partii')
  await expect(tooltip).toContainText('Twój głos głośno')
  await expect(tooltip).toContainText('Twoja partia wyciszona')
  await expect(tooltip).toContainText('zgodne tempo i moment rozpoczęcia')
  await expect(tooltip).toContainText('Nie wydziela głosów')
  await info.press('Escape')
  await page.mouse.move(0, 0)
  await expect(tooltip).not.toBeVisible()
  await info.click()
  await expect(info).toHaveAttribute('aria-expanded', 'true')
  await page.locator('.mixer').evaluate(element => element.scrollIntoView({ block: 'center' }))
  if (screenshots) await page.screenshot({ path: path.join(screenshots, 'mixer-info.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await info.scrollIntoViewIfNeeded()
  await expect(tooltip).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
